class AdminUserCreateSerializer(serializers.ModelSerializer):
    """Admin-side user provisioning (SRS VBB-FUN-UM-001, UC-006).

    A temporary password is supplied (or generated by the view) and the new
    user must rotate it on first login.
    """

    password = serializers.CharField(write_only=True, required=False)

    class Meta:
        model = User
        fields = [
            "id",
            "username",
            "email",
            "full_name",
            "phone_number",
            "role",
            "facility",
            "password",
        ]

    def create(self, validated_data):
        password = validated_data.pop("password", None) or generate_temp_password()
        user = User(**validated_data)
        user.set_password(password)
        user.must_change_password = True
        user.save()
        # Surface the generated temp password once so the admin can relay it.
        user._temporary_password = password
        return user


