class ChangePasswordSerializer(serializers.Serializer):
    current_password = serializers.CharField(write_only=True)
    new_password = serializers.CharField(write_only=True)

    def validate_current_password(self, value):
        user = self.context["request"].user
        if not user.check_password(value):
            raise serializers.ValidationError("Current password is incorrect.")
        return value

    def validate_new_password(self, value):
        validate_password(value, user=self.context["request"].user)
        return value


class EmailOrPhoneTokenSerializer(TokenObtainPairSerializer):
    """JWT obtain serializer keyed on email/phone, with role/facility claims.

    The ``username`` field accepts an email, phone number, or username; the
    configured ``EmailOrPhoneBackend`` resolves it (SRS VBB-FUN-UM-004). Token
    claims carry ``role`` and ``facility_id`` so the API can enforce the RBAC
    matrix without a DB lookup (SDS 2.3.3).
    """

    @classmethod
    def get_token(cls, user):
        token = super().get_token(user)
        token["role"] = user.role
        token["facility_id"] = str(user.facility_id) if user.facility_id else None
        token["full_name"] = user.full_name
        token["must_change_password"] = user.must_change_password
        return token
